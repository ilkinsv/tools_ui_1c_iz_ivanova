@dataclass
class ИнформацияОВерсии:
    """Класс для хранения информации о версии"""
    
    номер_мажорный: int = 0
    номер_минорный: int = 0
    номер_патч: int = 0
    дата_релиза: datetime = field(default_factory=datetime.now)
    описание: str = ""
    список_изменений: List[Dict[str, str]] = field(default_factory=list)
    
    def установить(self, мажорный: int, минорный: int, патч: int, 
                   описание: str = "", дата: Optional[datetime] = None):
        """Установка параметров версии"""
        if not isinstance(мажорный, int):
            raise ValueError("Мажорный номер должен быть числом")
        if not isinstance(минорный, int):
            raise ValueError("Минорный номер должен быть числом")
        if not isinstance(патч, int):
            raise ValueError("Патч номер должен быть числом")
        
        self.номер_мажорный = мажорный
        self.номер_минорный = минорный
        self.номер_патч = патч
        self.описание = описание
        self.дата_релиза = дата if дата else datetime.now()
        self.список_изменений = []
    
    def полная_версия(self) -> str:
        """Возвращает строку версии в формате "X.Y.Z" """
        return f"{self.номер_мажорный}.{self.номер_минорный}.{self.номер_патч}"
    
    def строка_версии(self) -> str:
        """Возвращает строку версии в формате "vX.Y.Z" """
        return f"v{self.номер_мажорный}.{self.номер_минорный}.{self.номер_патч}"
    
    def добавить_изменение(self, тип: str, описание: str):
        """Добавление записи об изменении"""
        self.список_изменений.append({"Тип": тип, "Описание": описание})
    
    def больше(self, другая_версия: 'ИнформацияОВерсии') -> bool:
        """Сравнение версий - больше ли текущая"""
        if self.номер_мажорный > другая_версия.номер_мажорный:
            return True
        if self.номер_мажорный < другая_версия.номер_мажорный:
            return False
        if self.номер_минорный > другая_версия.номер_минорный:
            return True
        if self.номер_минорный < другая_версия.номер_минорный:
            return False
        return self.номер_патч > другая_версия.номер_патч
    
    def равна(self, другая_версия: 'ИнформацияОВерсии') -> bool:
        """Проверка равенства версий"""
        return (self.номер_мажорный == другая_версия.номер_мажорный and
                self.номер_минорный == другая_версия.номер_минорный and
                self.номер_патч == другая_версия.номер_патч)
    
    def проверить_совместимость(self, другая_версия: 'ИнформацияОВерсии') -> bool:
        """Проверка совместимости версий"""
        if другая_версия.номер_мажорный > self.номер_мажорный:
            return False
        return True
    
    def to_dict(self) -> Dict[str, Any]:
        """Преобразование в словарь"""
        return {
            "Версия": self.полная_версия(),
            "Дата": self.дата_релиза.isoformat(),
            "Описание": self.описание,
            "Изменения": self.список_изменений
        }
    
    @classmethod
    def from_dict(cls, данные: Dict[str, Any]) -> 'ИнформацияОВерсии':
        """Создание из словаря"""
        части = данные.get("Версия", "0.0.0").split(".")
        версия = cls()
        версия.установить(
            int(части[0]),
            int(части[1]),
            int(части[2]),
            данные.get("Описание", "")
        )
        return версия


@dataclass
class Расширение:
    """Класс для создания расширений"""
    
    идентификатор: str = ""
    имя: str = ""
    версия: Optional[ИнформацияОВерсии] = None
    автор: str = ""
    описание: str = ""
    зависимости: List[Dict[str, Any]] = field(default_factory=list)
    точки_расширения: Dict[str, Callable] = field(default_factory=dict)
    активный: bool = True
    путь_к_файлу: str = ""
    
    def установить(self, идент: str, имя_расш: str, версия: ИнформацияОВерсии,
                   автор: str = "", описание: str = ""):
        """Инициализация расширения"""
        self.идентификатор = идент
        self.имя = имя_расш
        self.версия = версия
        self.автор = автор
        self.описание = описание
        self.зависимости = []
        self.точки_расширения = {}
        self.активный = True
    
    def добавить_зависимость(self, идентификатор_расширения: str, 
                             мин_версия: str, макс_версия: Optional[str] = None):
        """Добавление зависимости"""
        self.зависимости.append({
            "Идентификатор": идентификатор_расширения,
            "МинВерсия": мин_версия,
            "МаксВерсия": макс_версия
        })
    
    def добавить_точку_расширения(self, имя_точки: str, обработчик: Callable):
        """Регистрация точки расширения"""
        self.точки_расширения[имя_точки] = обработчик
    
    def получить_точку_расширения(self, имя_точки: str) -> Optional[Callable]:
        """Получение обработчика точки расширения"""
        return self.точки_расширения.get(имя_точки)
    
    def проверить_зависимости(self, реестр: 'РеестрРасширенийКласс') -> bool:
        """Проверка всех зависимостей"""
        for зависимость in self.зависимости:
            if not реестр.расширение_существует(зависимость["Идентификатор"]):
                return False
            
            расширение_зависимости = реестр.получить_расширение(
                зависимость["Идентификатор"]
            )
            
            if расширение_зависимости.версия:
                мин_версия_obj = ИнформацияОВерсии()
                части = зависимость["МинВерсия"].split(".")
                мин_версия_obj.установить(
                    int(части[0]), int(части[1]), int(части[2])
                )
                
                if not расширение_зависимости.версия.больше(мин_версия_obj):
                    return False
        
        return True


class РеестрРасширенийКласс:
    """Управление расширениями"""
    
    def __init__(self):
        self.расширения: Dict[str, Расширение] = {}
        self.точки_расширения_глобальные: Dict[str, List[Callable]] = {}
    
    def зарегистрировать_расширение(self, расширение: Расширение):
        """Регистрация расширения"""
        self.расширения[расширение.идентификатор] = расширение
        
        # Регистрация точек расширения
        for имя_точки, обработчик in расширение.точки_расширения.items():
            if имя_точки not in self.точки_расширения_глобальные:
                self.точки_расширения_глобальные[имя_точки] = []
            self.точки_расширения_глобальные[имя_точки].append(обработчик)
    
    def расширение_существует(self, идентификатор: str) -> bool:
        """Проверка существования расширения"""
        return идентификатор in self.расширения
    
    def получить_расширение(self, идентификатор: str) -> Optional[Расширение]:
        """Получение расширения по ID"""
        return self.расширения.get(идентификатор)
    
    def получить_все_расширения(self) -> Dict[str, Расширение]:
        """Получение всех расширений"""
        return self.расширения
    
    def вызвать_точку_расширения(self, имя_точки: str, параметры: Any = None):
        """Вызов точки расширения"""
        if имя_точки in self.точки_расширения_глобальные:
            for обработчик in self.точки_расширения_глобальные[имя_точки]:
                try:
                    if callable(обработчик):
                        обработчик(параметры)
                except Exception as e:
                    print(f"[ПРЕДУПРЕЖДЕНИЕ] Ошибка при вызове точки расширения "
                          f"'{имя_точки}': {e}")
    
    def количество_расширений(self) -> int:
        """Количество зарегистрированных расширений"""
        return len(self.расширения)


class МенеджерВерсийКласс:
    """Управление версиями"""
    
    def __init__(self):
        self.текущая_версия: Optional[ИнформацияОВерсии] = None
        self.история_версий: List[ИнформацияОВерсии] = []
        self.каталог_версий: str = ""
        self.конфигурация: Dict[str, Any] = {}
        
        # Инициализация каталога версий
        self.каталог_версий = str(Path.home() / ".versions7.0.3")
        Path(self.каталог_версий).mkdir(parents=True, exist_ok=True)
    
    def инициализировать_версию(self, мажорный: int, минорный: int, 
                                 патч: int, описание: str = ""):
        """Инициализация версии"""
        версия = ИнформацияОВерсии()
        версия.установить(мажорный, минорный, патч, описание)
        self.текущая_версия = версия
        self.история_версий.append(версия)
    
    def получить_текущую_версию(self) -> Optional[ИнформацияОВерсии]:
        """Получение текущей версии"""
        return self.текущая_версия
    
    def следующая_патч_версия(self) -> ИнформацияОВерсии:
        """Увеличение патч версии"""
        if self.текущая_версия is None:
            raise ValueError("Текущая версия не инициализирована")
        
        новый_патч = self.текущая_версия.номер_патч + 1
        if новый_патч > 999:
            raise ValueError(
                "Превышен максимальный номер патч-версии (999). "
                "Требуется увеличение минорной версии."
            )
        
        версия = ИнформацияОВерсии()
        версия.установить(
            self.текущая_версия.номер_мажорный,
            self.текущая_версия.номер_минорный,
            новый_патч,
            "Патч обновление"
        )
        
        self.история_версий.append(версия)
        self.текущая_версия = версия
        
        return версия
    
    def следующая_минорная_версия(self) -> ИнформацияОВерсии:
        """Увеличение минорной версии (+99)"""
        if self.текущая_версия is None:
            raise ValueError("Текущая версия не инициализирована")
        
        новый_минорный = self.текущая_версия.номер_минорный + 99
        новый_патч = 0
        
        версия = ИнформацияОВерсии()
        версия.установить(
            self.текущая_версия.номер_мажорный,
            новый_минорный,
            новый_патч,
            "Автоматическое обновление минорной версии"
        )
        
        self.история_версий.append(версия)
        self.текущая_версия = версия
        
        return версия
    
    def сохранить_конфигурацию(self, путь_к_файлу: str):
        """Сохранение конфигурации в JSON"""
        данные = {
            "Версия": self.текущая_версия.полная_версия() if self.текущая_версия else "0.0.0",
            "ДатаРелиза": self.текущая_версия.дата_релиза.isoformat() if self.текущая_версия else "",
            "Описание": self.текущая_версия.описание if self.текущая_версия else "",
            "История": [v.to_dict() for v in self.история_версий]
        }
        
        with open(путь_к_файлу, 'w', encoding='utf-8') as f:
            json.dump(данные, f, ensure_ascii=False, indent=2)
    
    def загрузить_конфигурацию(self, путь_к_файлу: str) -> bool:
        """Загрузка конфигурации из JSON"""
        if not os.path.exists(путь_к_файлу):
            return False
        
        with open(путь_к_файлу, 'r', encoding='utf-8') as f:
            данные = json.load(f)
        
        части = данные.get("Версия", "0.0.0").split(".")
        self.инициализировать_версию(
            int(части[0]),
            int(части[1]),
            int(части[2]),
            данные.get("Описание", "")
        )
        
        return True
    
    def проверить_совместимость_платформы(self, версия_платформы: str) -> bool:
        """Проверка совместимости платформы (минимум 8.3.12)"""
        try:
            части = версия_платформы.split(".")
            мажорный = int(части[0])
            минорный = int(части[1])
            патч = int(части[2])
            
            if мажорный < 8:
                return False
            if мажорный == 8 and минорный < 3:
                return False
            if мажорный == 8 and минорный == 3 and патч < 12:
                return False
            
            return True
        except (ValueError, IndexError):
            return False


class ЛоггерКласс:
    """Система логирования"""
    
    УРОВЕНЬ_ОШИБКА = 1
    УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ = 2
    УРОВЕНЬ_ИНФО = 3
    УРОВЕНЬ_ОТЛАДКА = 4
    
    def __init__(self):
        self.уровень_логирования = self.УРОВЕНЬ_ИНФО
        self.файл_лога = ""
        self.буфер_сообщений: List[str] = []
    
    def установить_уровень(self, уровень: int):
        """Установка уровня логирования"""
        self.уровень_логирования = уровень
    
    def установить_файл_лога(self, путь: str):
        """Установка файла лога"""
        self.файл_лога = путь
    
    def _записать_сообщение(self, уровень: int, тип: str, сообщение: str):
        """Внутренний метод записи сообщения"""
        if уровень > self.уровень_логирования:
            return
        
        время = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        текст = f"[{время}] [{тип}] {сообщение}"
        
        self.буфер_сообщений.append(текст)
        
        if self.файл_лога:
            try:
                with open(self.файл_лога, 'a', encoding='utf-8') as f:
                    f.write(текст + "\n")
            except Exception as e:
                print(f"Не удалось записать в лог-файл: {e}")
        
        print(текст)
    
    def записать_ошибка(self, сообщение: str):
        """Запись ошибки"""
        self._записать_сообщение(self.УРОВЕНЬ_ОШИБКА, "ОШИБКА", сообщение)
    
    def записать_предупреждение(self, сообщение: str):
        """Запись предупреждения"""
        self._записать_сообщение(self.УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ, "ПРЕДУПРЕЖДЕНИЕ", сообщение)
    
    def записать_инфо(self, сообщение: str):
        """Запись информации"""
        self._записать_сообщение(self.УРОВЕНЬ_ИНФО, "ИНФО", сообщение)
    
    def записать_отладка(self, сообщение: str):
        """Запись отладочной информации"""
        self._записать_сообщение(self.УРОВЕНЬ_ОТЛАДКА, "ОТЛАДКА", сообщение)
    
    def получить_все_сообщения(self) -> List[str]:
        """Получение всех сообщений"""
        return self.буфер_сообщений.copy()
    
    def очистить_буфер(self):
        """Очистка буфера"""
        self.буфер_сообщений.clear()


